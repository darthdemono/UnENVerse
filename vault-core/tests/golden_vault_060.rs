//! Golden reader for a vault written by release 0.60.0 (R20). The format policy is "the current
//! formats and the previous two", and the only golden vault before this one was written by 0.42.4,
//! which says nothing about the identity, lifecycle and operations tables added since.
//!
//! `fixtures/vault-0.60.x/` was made with the published 0.60.0 CLI (checksum verified against that
//! release's SHA256SUMS): `unv --init entry add` twice, then `entry set` on the first entry, so
//! the vault holds two entries and one replaced value in history. It is never regenerated by
//! CI; if a test here fails, the format changed and a migration is owed, not a new fixture.

use serde_json::Value;
use std::path::{Path, PathBuf};
use vault_core::{derive_key, open_db};

/// Test-only password; not a credential for anything.
const PW: &str = "golden-fixture-password";

fn copy_to_temp(name: &str) -> (PathBuf, PathBuf, PathBuf) {
    let src = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/vault-0.60.x");
    let tmp = std::env::temp_dir().join(format!("unv-golden060-{name}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&tmp);
    std::fs::create_dir_all(&tmp).unwrap();
    let db = tmp.join("vault.db");
    let salt = tmp.join("vault.salt");
    std::fs::copy(src.join("vault.db"), &db).unwrap();
    std::fs::copy(src.join("vault.salt"), &salt).unwrap();
    (tmp, db, salt)
}

fn open(db: &Path, salt: &Path) -> rusqlite::Connection {
    let salt = std::fs::read(salt).unwrap();
    let key = derive_key(PW, &salt).unwrap();
    open_db(db, &key).expect("a 0.60.0 vault must open")
}

#[test]
fn a_0_60_vault_opens_verifies_and_keeps_its_entries_and_history() {
    let (tmp, db, salt) = copy_to_temp("open");
    let conn = open(&db, &salt);
    let ok: String = conn
        .query_row("PRAGMA integrity_check", [], |r| r.get(0))
        .unwrap();
    assert_eq!(ok, "ok");
    assert!(vault_core::verify_vault_integrity(&conn).unwrap());

    vault_core::init_schema(&conn).unwrap();
    vault_core::ensure_current_schema(&conn).unwrap();
    let migrations: Vec<i64> = conn
        .prepare("SELECT id FROM schema_migrations ORDER BY id")
        .unwrap()
        .query_map([], |row| row.get(0))
        .unwrap()
        .map(|row| row.unwrap())
        .collect();
    assert!(
        migrations.starts_with(&[1, 2, 3, 4, 5]),
        "migrations after opening: {migrations:?}"
    );

    let v = vault_core::load_vault(&conn).unwrap().unwrap();
    let entries = v["api_keys"].as_array().unwrap();
    assert_eq!(entries.len(), 2);
    let find = |name: &str| -> &Value {
        entries
            .iter()
            .find(|e| e["provider"] == name)
            .unwrap_or_else(|| panic!("no entry {name}"))
    };
    assert_eq!(find("Golden Stripe")["api_key"], "golden-token-value-0002");
    let github = find("Golden GitHub");
    assert_eq!(github["api_key"], "golden-token-value-0003");
    // The replaced value is kept as history, and the current one is not in it.
    let history = github["version_history"].to_string();
    assert!(history.contains("golden-token-value-0001"), "{history}");
    assert!(!history.contains("golden-token-value-0003"), "{history}");
    drop(conn);
    let _ = std::fs::remove_dir_all(tmp);
}

#[test]
fn the_instance_identity_a_0_60_vault_carries_is_still_live_and_active() {
    let (tmp, db, salt) = copy_to_temp("identity");
    let conn = open(&db, &salt);
    vault_core::init_schema(&conn).unwrap();
    let id = vault_core::identity::ensure(&conn).unwrap();
    let id = serde_json::to_value(&id).unwrap();
    assert_eq!(id["role"], "active");
    assert!(!id["vault_id"].as_str().unwrap().is_empty());
    assert!(!id["instance_id"].as_str().unwrap().is_empty());
    drop(conn);
    let _ = std::fs::remove_dir_all(tmp);
}

#[test]
fn a_wrong_password_is_refused_with_the_same_words_as_for_a_new_vault() {
    let (tmp, db, salt) = copy_to_temp("wrong");
    let salt = std::fs::read(salt).unwrap();
    let key = derive_key("not-the-fixture-password", &salt).unwrap();
    let err = open_db(&db, &key).unwrap_err();
    assert_eq!(err, "Wrong master password");
    let _ = std::fs::remove_dir_all(tmp);
}
