/**
 * Branch coverage for the stack interpreter, driven by a synthetic adapter so
 * every node kind and every YAML writer path runs, not just those the shipped
 * descriptor happens to use.
 */
import { describe, it, expect } from 'vitest';
import {
  renderStack,
  stackAdapter,
  isStackProjectType,
  newStackChunk,
  stackStarterChunks,
  stackChunkSpec,
  type StackAdapter,
} from '../src/ts/stack';

const spec = {
  type: 'svc',
  label: 'Svc',
  fields: [
    { key: 'name' },
    { key: 'pw', secret: true },
    { key: 'ports', kind: 'list' },
    { key: 'on', kind: 'bool' },
    { key: 'n' },
    { key: 'grp', default: 'g0' },
  ],
};

function adapter(output: unknown, starter: { type: string; name: string }[] = []): StackAdapter {
  return {
    id: 't',
    label: 'T',
    abbr: 'T',
    description: '',
    file: 't.yml',
    chunks: [spec],
    starter,
    output,
  } as any;
}

const chunk = (name: string, vals: Record<string, string>, extra: object = {}) =>
  ({
    id: name,
    name,
    chunk_type: 'svc',
    fields: Object.entries(vals).map(([key, value]) => ({ key, value })),
    ...extra,
  }) as any;

const render = (
  output: unknown,
  chunks: any[],
  resolve: (r: string, s: boolean) => string = (r) => r,
) => renderStack(adapter(output), { chunks } as any, resolve);

describe('stack interpreter', () => {
  it('looks adapters up and rejects unknown or empty ids', () => {
    expect(stackAdapter(null)).toBeUndefined();
    expect(stackAdapter('nope')).toBeUndefined();
    expect(isStackProjectType('nope')).toBe(false);
    expect(isStackProjectType(undefined)).toBe(false);
  });

  it('scalars: literals, null, non-integer numbers', () => {
    const out = render(
      {
        map: [
          ['a', 'yes'],
          ['b', true],
          ['c', 3],
          ['d', 1.5],
          ['e', null],
          ['f', 'plain'],
        ],
      },
      [],
    );
    expect(out).toContain('a: "yes"');
    expect(out).toContain('b: true');
    expect(out).toContain('c: 3');
    expect(out).not.toContain('d:');
    expect(out).toContain('f: plain');
    expect(render({ map: [['k', '']] }, [])).toContain('k: ""');
  });

  it('field nodes: str, fmt, list, bool, int, @name, blank, no current chunk', () => {
    const c = chunk('web', { name: 'x', ports: 'a, b\nc', on: 'Yes', n: '12', pw: 'sec' });
    const out = render(
      {
        each: 'svc',
        node: {
          map: [
            ['nm', { f: '@name' }],
            ['fmt', { f: 'name', fmt: 'pre-{}' }],
            ['ports', { f: 'ports', as: 'list' }],
            ['on', { f: 'on', as: 'bool' }],
            ['n', { f: 'n', as: 'int' }],
            ['pw', { f: 'pw' }],
            ['blank', { f: 'grp' }],
          ],
        },
      },
      [c],
      (raw, secret) => (secret ? `<${raw}>` : raw),
    );
    expect(out).toContain('nm: web');
    expect(out).toContain('fmt: pre-x');
    expect(out).toMatch(/ports:\n\s+- a\n\s+- b\n\s+- c/);
    expect(out).toContain('"on": true');
    expect(out).toContain('"n": 12');
    expect(out).toContain('pw: "<sec>"');
    expect(out).not.toContain('blank');
    // Top-level field without a current chunk resolves to nothing.
    expect(render({ f: 'name' }, [c])).toBe('# Generated by UnENVerse\n');
  });

  it('bool/int/list edge values', () => {
    const c = chunk('w', { on: 'maybe', n: 'abc', ports: ' , ', name: 'off' });
    const out = render(
      {
        each: 'svc',
        node: {
          map: [
            ['on', { f: 'on', as: 'bool' }],
            ['n', { f: 'n', as: 'int' }],
            ['p', { f: 'ports', as: 'list' }],
            ['off', { f: 'name', as: 'bool' }],
          ],
        },
      },
      [c],
    );
    expect(out).not.toContain('"on":');
    expect(out).toContain('"n": abc');
    expect(out).not.toMatch(/\bp:/);
    expect(out).toContain('"off": false');
  });

  it('skips disabled chunks, unknown chunk types and singleton misses', () => {
    const on = chunk('a', { name: 'x' });
    const off = chunk('b', { name: 'y' }, { disabled: true });
    expect(render({ each: 'svc', node: { f: 'name' } }, [on, off])).toBe(
      '# Generated by UnENVerse\n- x\n',
    );
    expect(render({ each: 'ghost', node: { f: 'name' } }, [on])).toBe('# Generated by UnENVerse\n');
    expect(
      render({ map: [['k', { each: 'ghost', node: { f: 'name' }, keep: true }]] }, [on]),
    ).toContain('k: []');
    expect(render({ singleton: 'svc', node: { map: [['n', { f: 'name' }]] } }, [on])).toContain(
      '"n": x',
    );
    expect(render({ singleton: 'svc', node: { f: 'name' } }, [])).toBe(
      '# Generated by UnENVerse\n',
    );
  });

  it('map/list keep flags and the empty renderings', () => {
    expect(render({ map: [['k', { map: [['a', { f: 'name' }]], keep: true }]] }, [])).toContain(
      'k: {}',
    );
    expect(render({ map: [['a', { f: 'name' }]] }, [])).toBe('# Generated by UnENVerse\n');
    expect(
      render(
        {
          map: [
            ['m', { map: [], keep: true }],
            ['l', { list: [], keep: true }],
            [
              's',
              {
                list: [
                  'a',
                  { list: ['b'] },
                  { list: [], keep: true },
                  { map: [['k', 'v']] },
                  { map: [], keep: true },
                  true,
                  2,
                ],
              },
            ],
          ],
        },
        [],
      ),
    ).toMatch(
      /m: \{\}\nl: \[\]\ns:\n\s+- a\n\s+-\n\s+- b\n\s+- \[\]\n\s+- k: v\n\s+- \{\}\n\s+- true\n\s+- 2/,
    );
    expect(render({ list: [{ f: 'name' }] }, [])).toBe('# Generated by UnENVerse\n');
    // top-level list with a keep flag
    expect(render({ list: [], keep: true }, [])).toBe('# Generated by UnENVerse\n');
  });

  it('group: by field, default, repeat, skipped nulls', () => {
    const cs = [
      chunk('a', { name: 'xx', grp: 'g1' }),
      chunk('b', { name: 'yy', grp: 'g1' }),
      chunk('c', { name: 'zz', grp: '' }),
      chunk('d', { grp: 'g2' }),
    ];
    const out = render(
      { group: { of: 'svc', by: 'grp', default: 'dflt', item: { f: 'name' } } },
      cs,
    );
    expect(out).toMatch(/- g1:\n\s+- xx\n\s+- yy\n- dflt:\n\s+- zz/);
    expect(out).not.toContain('g2');
    const noDefault = render({ group: { of: 'svc', by: 'grp', item: { f: 'name' } } }, [
      chunk('e', { name: 'q', grp: '' }),
    ]);
    expect(noDefault).toContain('- "":');
    expect(
      render(
        { map: [['k', { group: { of: 'svc', by: 'grp', item: { f: 'name' } }, keep: true }]] },
        [],
      ),
    ).toContain('k: []');
    expect(render({ group: { of: 'svc', by: 'grp', item: { f: 'name' } } }, [])).toBe(
      '# Generated by UnENVerse\n',
    );
  });

  it('entry: string key, non-string key, missing value, value', () => {
    const c = chunk('a', { name: 'k1', n: '5' });
    const out = render(
      { each: 'svc', node: { entry: { key: { f: 'name' }, value: { f: 'n' } } } },
      [c],
    );
    expect(out).toMatch(/- k1: "5"/);
    expect(render({ each: 'svc', node: { entry: { key: { f: 'name' } } } }, [c])).toMatch(
      /k1: \{\}/,
    );
    expect(render({ each: 'svc', node: { entry: { key: { f: 'n', as: 'int' } } } }, [c])).toBe(
      '# Generated by UnENVerse\n',
    );
  });

  it('when: only if a listed field has a value', () => {
    const c = chunk('a', { name: 'x' });
    const node = (f: string) => ({ each: 'svc', node: { when: [f], node: { f: 'name' } } });
    expect(render(node('name'), [c])).toContain('- x');
    expect(render(node('pw'), [c])).toBe('# Generated by UnENVerse\n');
  });

  it('chunks with no fields array and non-string values read as empty', () => {
    const bare = { id: 'z', name: 'z', chunk_type: 'svc' } as any;
    const weird = {
      id: 'w',
      name: 'w',
      chunk_type: 'svc',
      fields: [{ key: 'name', value: 5 }],
    } as any;
    expect(render({ each: 'svc', node: { f: 'name' } }, [bare, weird])).toBe(
      '# Generated by UnENVerse\n',
    );
  });

  it('an unnamed chunk reads @name as blank, and a project with no chunks renders nothing', () => {
    const c = { id: 'u', chunk_type: 'svc', fields: [] } as any;
    expect(render({ each: 'svc', node: { f: '@name' } }, [c])).toBe('# Generated by UnENVerse\n');
    expect(renderStack(adapter({ f: 'x' }), {} as any, (r) => r)).toBe(
      '# Generated by UnENVerse\n',
    );
  });

  it('builds new and starter chunks from a spec', () => {
    const ad = adapter(null, [
      { type: 'svc', name: 'one' },
      { type: 'gone', name: 'two' },
    ]);
    const made = stackStarterChunks(ad);
    expect(made).toHaveLength(1);
    const kinds = Object.fromEntries(made[0].fields!.map((f) => [f.key, f.field_type]));
    expect(kinds).toMatchObject({ pw: 'secret', ports: 'list', name: 'var' });
    expect(made[0].fields!.find((f) => f.key === 'grp')!.value).toBe('g0');
    expect(stackChunkSpec(ad, 'svc')).toBeDefined();
    expect(newStackChunk(spec as any, 'n').name).toBe('n');
  });
});
